/**
 * Write a migration file from the schema drift between source and target.
 *
 * Shared by `migrate create` and the MCP `create_migration` tool, so the file
 * an agent writes is the file the CLI would.
 */
import { writeFile, mkdir } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { runDbDiff, isDestructiveSql } from './dbdiff.js'
import { RolesCheck } from './checks/roles.js'
import type { CheckContext } from './checks/base.js'
import { DEFAULT_MIGRATIONS_DIR } from './checks/migrations.js'
import { pgQuery } from './db.js'
import { DEFAULT_IGNORE_SCHEMAS } from './defaults.js'
import { splitSqlStatements } from './utils/sql-split.js'
import { slugify } from './utils/strings.js'
import { targetFingerprint, writtenAgainstLine } from './written-against.js'
import type { SupaForgeConfig } from './types/config.js'

export interface MigrationFile {
  /** Where it was written; undefined when there was no drift to write. */
  filePath?: string
  /** Statements in it that drop or delete data. */
  destructive: string[]
}

/** The directory migrations are written to, as configured. */
export function migrationsDir(config: SupaForgeConfig, cwd = process.cwd()): string {
  return resolve(cwd, config.checks?.migrations?.dir ?? DEFAULT_MIGRATIONS_DIR)
}

export async function writeMigrationFile(opts: { config: SupaForgeConfig; name: string; dir: string }): Promise<MigrationFile> {
  const { config, name, dir } = opts
  const sourceEnv = config.environments[config.source!]
  const targetEnv = config.environments[config.target!]
  const ignoreSchemas = config.ignoreSchemas ?? DEFAULT_IGNORE_SCHEMAS

  const result = await runDbDiff({
    sourceUrl: sourceEnv.dbUrl,
    targetUrl: targetEnv.dbUrl,
    type: 'schema',
    include: 'both',
    ignoreSchemas,
  })

  // The grants on what it makes, written out: the file is replayed where
  // default privileges differ — a new project, a preview branch, a local
  // reset — and Supabase no longer grants the Data API roles on new tables.
  const grants = (await new RolesCheck(pgQuery, { explicit: true }).scan({
    source: sourceEnv, target: targetEnv, config,
  } as CheckContext)).filter(i => i.id.startsWith('roles-grant-') && i.sql?.up)

  if (!result.up.trim() && grants.length === 0) return { destructive: [] }

  // Said when the file is written, not first when `migrate run` refuses it:
  // a diff in which the target has a table the source lacks becomes a
  // DROP TABLE here, and the file looks like any other.
  const destructive = splitSqlStatements(result.up).filter(isDestructiveSql)

  // The target as the file was written against it, for migrate run to check.
  const digest = await targetFingerprint(targetEnv.dbUrl, ignoreSchemas).catch(() => undefined)
  const lines: string[] = [
    `-- Migration: ${name}`,
    `-- Generated by supaforge migrate create`,
    `-- Source: ${config.source!} → Target: ${config.target!}`,
    ...(digest ? [writtenAgainstLine(config.target!, digest)] : []),
    ...(destructive.length > 0
      ? [`-- WARNING: ${destructive.length} destructive statement(s) — drops or deletes data. Review before running.`]
      : []),
    '',
    result.up,
    ...(grants.length > 0 ? ['', '-- Grants', ...grants.map(i => i.sql!.up)] : []),
  ]

  if (result.down.trim() || grants.length > 0) {
    lines.push(
      '',
      '-- ==================== DOWN ====================',
      '-- To revert this migration, run the SQL below manually:',
      '--',
      ...[...grants.map(i => i.sql?.down ?? '').filter(Boolean).reverse(), result.down].join('\n').split('\n').map(l => `-- ${l}`),
    )
  }

  await mkdir(dir, { recursive: true })
  const filePath = join(dir, `${generateTimestamp()}_${slugify(name)}.sql`)
  await writeFile(filePath, lines.join('\n') + '\n', 'utf8')
  return { filePath, destructive }
}

/** Generate a UTC timestamp in Supabase migration format: YYYYMMDDHHmmss */
export function generateTimestamp(): string {
  const now = new Date()
  return [
    now.getUTCFullYear(),
    pad(now.getUTCMonth() + 1),
    pad(now.getUTCDate()),
    pad(now.getUTCHours()),
    pad(now.getUTCMinutes()),
    pad(now.getUTCSeconds()),
  ].join('')
}

function pad(n: number): string {
  return String(n).padStart(2, '0')
}
