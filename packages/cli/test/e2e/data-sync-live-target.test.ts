/**
 * Reference-data sync into a target that is in use: it has triggers of its
 * own, and a table whose rows refer to each other.
 *
 * - The target's triggers fired on every synced row. An `updated_at` trigger
 *   overwrote the value just synced, so the tables never matched; an audit
 *   trigger wrote log rows that collided with the log rows being synced, and
 *   the apply rolled back.
 * - A tree whose node was moved under a newer one needs a row written after
 *   it: the insert failed its own table's foreign key, and the apply rolled
 *   back.
 *
 * Verdicts are read from the target database, not from SupaForge's report.
 */
import { describe, it, expect, beforeAll, afterAll } from 'vitest'
import { PgHarness } from '../harness/PgHarness.js'
import { describeWithContainers } from '../harness/containers.js'

const describeE2E = describeWithContainers()

const TABLES = `
  CREATE TABLE public.touchy (id int PRIMARY KEY, v text, updated_at timestamptz);
  CREATE TABLE public.touchy_log (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, touchy_id int, op text);
  CREATE TABLE public.always_log (touchy_id int);
  CREATE FUNCTION public.touch() RETURNS trigger LANGUAGE plpgsql AS $f$
    BEGIN NEW.updated_at := '2000-01-01'; INSERT INTO public.touchy_log (touchy_id, op) VALUES (NEW.id, TG_OP); RETURN NEW; END $f$;
  CREATE FUNCTION public.always() RETURNS trigger LANGUAGE plpgsql AS $f$
    BEGIN INSERT INTO public.always_log VALUES (NEW.id); RETURN NEW; END $f$;
  CREATE TRIGGER touch BEFORE INSERT OR UPDATE ON public.touchy FOR EACH ROW EXECUTE FUNCTION public.touch();
  CREATE TRIGGER always AFTER INSERT ON public.touchy FOR EACH ROW EXECUTE FUNCTION public.always();
  ALTER TABLE public.touchy ENABLE ALWAYS TRIGGER always;
  CREATE TABLE public.tree (id int PRIMARY KEY, parent int REFERENCES public.tree, label text);
`

/** Rows as written with the triggers off, as an app's history would leave them. */
const SOURCE_ROWS = `
  ALTER TABLE public.touchy DISABLE TRIGGER USER;
  INSERT INTO public.touchy VALUES (1, 'one', '2026-01-01 00:00:00+00'), (2, 'two', '2026-02-02 00:00:00+00');
  INSERT INTO public.touchy_log (touchy_id, op) VALUES (1, 'INSERT'), (2, 'INSERT');
  ALTER TABLE public.touchy ENABLE TRIGGER USER;
  -- Each node under the next one: every row needs one written after it.
  INSERT INTO public.tree VALUES (2000, NULL, 'root');
  INSERT INTO public.tree SELECT g, g + 1, 'n' || g FROM generate_series(1999, 1, -1) g;
`

describeE2E('e2e: data sync into a target with triggers and a self-referencing table', () => {
  let h: PgHarness

  beforeAll(async () => {
    h = new PgHarness({ verbose: !!process.env.E2E_VERBOSE, keep: !!process.env.E2E_KEEP })
    await h.up()
    await h.applySql('source', TABLES + SOURCE_ROWS)
    await h.applySql('target', TABLES)
  }, 300_000)

  afterAll(async () => { await h?.down() }, 120_000)

  const rows = (role: 'source' | 'target', table: string, cols = '*') =>
    h.sql(role, `SELECT coalesce(string_agg(x::text, '|' ORDER BY x::text COLLATE "C"), '') FROM (SELECT ${cols} FROM public.${table}) x`)

  it('syncs the rows as they are, with the target\'s triggers held off and put back', async () => {
    const ws = await h.workspace({ checks: { data: { tables: ['touchy', 'touchy_log', 'tree'] } } })
    const run = await h.cli(['diff', '--check', 'data', '--apply', '--json'], { cwd: ws })
    const result = JSON.parse(run.stdout)
    expect(result.errors).toEqual([])

    expect(await rows('target', 'touchy')).toBe(await rows('source', 'touchy'))
    expect(await rows('target', 'touchy_log')).toBe(await rows('source', 'touchy_log'))
    expect(await rows('target', 'tree')).toBe(await rows('source', 'tree'))
    expect(await h.sql('target', 'SELECT count(*) FROM public.tree')).toBe('2000')

    // Held off, and back as they were: the ordinary trigger on, the ALWAYS one
    // still ALWAYS — and that one fired, as it would under replication.
    expect(await h.sql('target', `SELECT string_agg(tgname || '=' || tgenabled::text, ',' ORDER BY tgname) FROM pg_trigger
      WHERE tgrelid = 'public.touchy'::regclass AND NOT tgisinternal`)).toBe('always=A,touch=O')
    expect(await h.sql('target', 'SELECT count(*) FROM public.always_log')).toBe('2')
    expect(result.notes.join(' ')).toContain('Held off trigger "touch" on touchy')

    // The tree's key is checked and made NOT DEFERRABLE again.
    expect(await h.sql('target', `SELECT condeferrable FROM pg_constraint WHERE conname = 'tree_parent_fkey'`)).toBe('f')

    // Converged: nothing left to sync.
    const again = JSON.parse((await h.cli(['diff', '--check', 'data', '--json'], { cwd: ws })).stdout)
    expect(again.checks.flatMap((c: { issues: unknown[] }) => c.issues)).toEqual([])
  }, 300_000)

  it('rolls everything back when a row is still orphaned at the end', async () => {
    await h.applySql('source', `
      CREATE TABLE public.loose (id int PRIMARY KEY, parent int, label text);
      INSERT INTO public.loose VALUES (1, 2, 'child first'), (2, NULL, 'parent'), (3, 99, 'orphan');
      INSERT INTO public.touchy VALUES (3, 'three', NULL);`)
    await h.applySql('target', 'CREATE TABLE public.loose (id int PRIMARY KEY, parent int REFERENCES public.loose, label text);')
    const before = await rows('target', 'touchy')

    const ws = await h.workspace({ checks: { data: { tables: ['touchy', 'loose'] } } })
    const run = await h.cli(['diff', '--check', 'data', '--apply', '--json'], { cwd: ws })
    const result = JSON.parse(run.stdout)
    expect(run.code).toBe(1)
    expect(result.errors[0].error).toMatch(/loose_parent_fkey/)
    expect(result.rolledBack.length).toBeGreaterThan(0)
    expect(result.rolledBack[0]).not.toHaveProperty('sql')

    expect(await h.sql('target', 'SELECT count(*) FROM public.loose')).toBe('0')
    expect(await rows('target', 'touchy')).toBe(before)
    expect(await h.sql('target', `SELECT condeferrable FROM pg_constraint WHERE conname = 'loose_parent_fkey'`)).toBe('f')
    expect(await h.sql('target', `SELECT tgenabled FROM pg_trigger WHERE tgname = 'touch'`)).toBe('O')
  }, 300_000)

  it('says so when the triggers cannot be held off, because the role does not own the table', async () => {
    const STAMPED = `
      CREATE TABLE public.stamped (id int PRIMARY KEY, v text, updated_at timestamptz);
      CREATE FUNCTION public.stamp() RETURNS trigger LANGUAGE plpgsql AS $f$ BEGIN NEW.updated_at := '2000-01-01'; RETURN NEW; END $f$;
      CREATE TRIGGER stamp BEFORE INSERT OR UPDATE ON public.stamped FOR EACH ROW EXECUTE FUNCTION public.stamp();`
    await h.applySql('source', STAMPED + `
      ALTER TABLE public.stamped DISABLE TRIGGER stamp;
      INSERT INTO public.stamped VALUES (1, 'one', '2026-01-01 00:00:00+00');`)
    await h.applySql('target', STAMPED + `
      CREATE ROLE sf_syncer LOGIN PASSWORD 'sf_syncer';
      GRANT USAGE ON SCHEMA public TO sf_syncer;
      GRANT SELECT, INSERT, UPDATE, DELETE ON public.stamped TO sf_syncer;`)
    const target = h.connectionString('target').replace(/\/\/[^@]*@/, '//sf_syncer:sf_syncer@')
    const ws = await h.workspace({
      environments: { source: { dbUrl: h.connectionString('source') }, target: { dbUrl: target } },
      checks: { data: { tables: ['stamped'] } },
    })
    const run = await h.cli(['diff', '--check', 'data', '--apply', '--json'], { cwd: ws })
    const result = JSON.parse(run.stdout)
    expect(result.errors).toEqual([])
    expect(result.warnings.join(' ')).toMatch(/Triggers on stamped fired .*does not own the table/)
    // Which is why: the trigger rewrote the value synced.
    expect(await h.sql('target', 'SELECT updated_at = \'2000-01-01\' FROM public.stamped WHERE id = 1')).toBe('t')
  }, 300_000)
})
