import { describe, it, expect } from 'vitest'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { DbDiffOutputReader, DOWN_MARKER, readDbDiffStatements, splitStatements, UP_MARKER } from '../src/dbdiff-output.js'
import { parseDbDiffOutput } from '../src/dbdiff.js'

/** What reading the whole file as one string gave: the reference. */
function reference(output: string): { up: string[]; down: string[] } {
  const { up, down } = parseDbDiffOutput(output)
  return { up: splitStatements(up), down: splitStatements(down) }
}

/** The reader, given the text in pieces of the sizes `sizes` cycles through. */
function streamed(output: string, sizes: number[]): { up: string[]; down: string[] } {
  const reader = new DbDiffOutputReader()
  let at = 0
  for (let k = 0; at < output.length; k++) {
    const size = sizes[k % sizes.length]
    reader.push(output.slice(at, at + size))
    at += size
  }
  return reader.end()
}

function rng(seed: number) {
  let s = seed >>> 0
  return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 2 ** 32)
}

/** Values that hold what can end or hide a statement. */
const VALUES = ["'plain'", "'semi; colon'", "'it''s'", "'line\nbreak; still'", "'-- not a comment'", "'/* nor this */'",
  "'$$ not dollar $$'", "'\"q\"'", "NULL", '42', "'é 🎉'", "'" + UP_MARKER.slice(0, 10) + "'", "$$dollar; body$$", "$t$a;b$t$"]

function output(next: () => number, shape: 'both' | 'up-only' | 'none' | 'down-only'): string {
  const statement = () => {
    const v = () => VALUES[Math.floor(next() * VALUES.length)]
    const r = next()
    const table = next() < 0.5 ? '"plans"' : '"app"."orders"'
    if (r < 0.5) return `INSERT INTO ${table} ("id","name") VALUES(${v()},${v()});`
    if (r < 0.8) return `UPDATE ${table} SET "name" = ${v()} WHERE "id" = ${v()};`
    return `DELETE FROM ${table} WHERE "id" = ${v()};`
  }
  const many = () => Array.from({ length: 1 + Math.floor(next() * 30) }, () => (next() < 0.1 ? '-- a comment\n' : '') + statement()).join('\n')
  const header = '-- generated by dbdiff\n/* block\n /* nested */ comment */\n'
  if (shape === 'none') return `${header}${many()}\n`
  if (shape === 'up-only') return `${header}\n${UP_MARKER}\n${many()}\n`
  if (shape === 'down-only') return `${header}\n${DOWN_MARKER}\n${many()}\n`
  return `${header}\n${UP_MARKER}\n${many()}\n\n${DOWN_MARKER}\n${many()}`
}

describe('DbDiffOutputReader', () => {
  it('gives what splitting the whole output gave, for every shape and every way of cutting it up', () => {
    for (let seed = 1; seed <= 400; seed++) {
      const next = rng(seed)
      const shape = (['both', 'up-only', 'none', 'down-only'] as const)[seed % 4]
      const text = output(next, shape)
      const expected = reference(text)
      expect(expected.up.length + expected.down.length, `seed ${seed}`).toBeGreaterThan(0)
      for (const sizes of [[1], [2, 3], [7], [64], [1 << 20], [Math.ceil(next() * 50) + 1]]) {
        expect(streamed(text, sizes), `seed ${seed}, pieces ${sizes}`).toEqual(expected)
      }
    }
  })

  it('reads a file as a stream', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'sf-dbdiff-out-'))
    try {
      const text = output(rng(7), 'both')
      const file = join(dir, 'out.sql')
      writeFileSync(file, text)
      expect(await readDbDiffStatements(file)).toEqual(reference(text))
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  it('holds no more than a statement and a line at a time, however long the output', () => {
    // 200,000 rows: a string of all of it is what this avoids.
    const reader = new DbDiffOutputReader()
    reader.push(`${UP_MARKER}\n`)
    const row = (i: number) => `INSERT INTO "t" ("id","body") VALUES('${i}','${'x'.repeat(100)}');\n`
    let pieces = ''
    for (let i = 0; i < 200_000; i++) {
      pieces += row(i)
      if (pieces.length > 4096) { reader.push(pieces); pieces = '' }
      expect((reader as unknown as { pending: string }).pending.length).toBeLessThan(8192)
    }
    reader.push(pieces)
    const { up } = reader.end()
    expect(up).toHaveLength(200_000)
    expect(up[199_999]).toBe(row(199_999).trim())
  })
})
