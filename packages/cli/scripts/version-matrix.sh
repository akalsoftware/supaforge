#!/bin/bash
# One pair of the version and platform matrix: SupaForge from SOURCE to
# TARGET, each one of sb15, sb17 (Supabase's Postgres images) or pg14..pg18,
# on two servers this script starts in containers.
#
#   p1  a full fixture on the source, an empty target: diff --apply (schema
#       and reference data); the target's state must then equal the source's,
#       and a re-diff must leave nothing of the fixture.
#   p2  rows on the target, then the source moves on (column and table
#       renames, a retype under a generated column, views and a policy, an
#       enum label, a view widened, a function replaced): diff --check schema
#       --apply --prove; the rows must stay and the state must match.
#   p3  a plain target: snapshot the source, restore into a fresh database
#       on the target's server; the state must equal the source's.
#
# Verdicts are read from the databases. What only one version or platform
# can hold is named mx_v1* and left out of the comparison.
#
#   scripts/version-matrix.sh SOURCE TARGET
set -u
CLI=$(cd "$(dirname "$0")/.." && pwd)
SF=${SF:-$CLI}
OUT=${OUT:-$(mktemp -d)}; mkdir -p "$OUT"; RES=$OUT/results.tsv; : > "$RES"
SOURCE=$1 TARGET=$2
SB15_IMAGE=${SB15_IMAGE:-public.ecr.aws/supabase/postgres:15.8.1.085}
SB17_IMAGE=${SB17_IMAGE:-public.ecr.aws/supabase/postgres:17.6.1.176}

image(){ case $1 in sb15) echo "$SB15_IMAGE";; sb17) echo "$SB17_IMAGE";; pg1[4-8]) echo "docker.io/library/postgres:${1#pg}";; *) echo "unknown node $1" >&2; exit 2;; esac; }
kind(){ [[ $1 == sb* ]] && echo sb || echo pg; }
version(){ echo "${1:2}"; }
# role → "kind version container port"
info(){ if [ $2 = src ]; then echo "$(kind $1) $(version $1) mx-src 56001"; else echo "$(kind $1) $(version $1) mx-tgt 56002"; fi; }

start(){ local node=$1 c=$2 port=$3
  docker rm -f $c >/dev/null 2>&1
  if [ $(kind $node) = sb ]; then
    docker run -d --name $c -p 127.0.0.1:$port:5432 -e POSTGRES_PASSWORD=smokepass \
      -e JWT_SECRET=ci-only-jwt-secret-at-least-32-characters-long "$(image $node)" postgres -D /etc/postgresql >/dev/null
  else
    docker run -d --name $c -p 127.0.0.1:$port:5432 -e POSTGRES_PASSWORD=rootpass "$(image $node)" >/dev/null
  fi
  for _ in $(seq 180); do
    q $(kind $node) $c $port postgres -c 'SELECT 1' >/dev/null 2>&1 && return 0
    sleep 1
  done
  echo "$c did not start"; docker logs $c 2>&1 | tail -20; exit 1
}

# psql as an admin on a node's database: q KIND CONTAINER PORT DB [psql args]
q(){ local kind=$1 c=$2 p=$3 db=$4; shift 4
  if [ $kind = sb ]; then docker exec -i -e PGPASSWORD=smokepass $c psql -h localhost -U supabase_admin -d $db -q -X -At -v ON_ERROR_STOP=1 "$@"
  else docker exec -i $c psql -U postgres -d $db -q -X -At -v ON_ERROR_STOP=1 "$@"; fi; }

# The fixture, for a source of KIND and VERSION.
fixture(){ local kind=$1 v=$2
cat <<'SQL'
CREATE SCHEMA mx_app;
CREATE TYPE public.mx_status AS ENUM ('new', 'paid', 'shipped');
CREATE DOMAIN public.mx_email AS text CHECK (VALUE LIKE '%@%');
CREATE TYPE public.mx_money AS (amount numeric(12,2), currency char(3));
CREATE TYPE public.mx_span AS RANGE (subtype = int4);
CREATE SEQUENCE public.mx_ticket_seq START 1000;
CREATE TABLE public.mx_customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email public.mx_email NOT NULL UNIQUE,
  name text NOT NULL,
  status public.mx_status NOT NULL DEFAULT 'new',
  created_at timestamptz NOT NULL DEFAULT now(),
  tags text[] DEFAULT '{}',
  meta jsonb);
CREATE TABLE public.mx_orders (
  id bigserial PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES public.mx_customers (id) ON DELETE CASCADE,
  total numeric(12,2) NOT NULL CHECK (total >= 0),
  kind varchar(10) CHECK (kind IN ('web', 'shop')),
  total_gross numeric(14,2) GENERATED ALWAYS AS (total * 1.2) STORED,
  ticket int DEFAULT nextval('public.mx_ticket_seq'),
  price public.mx_money,
  span public.mx_span);
CREATE INDEX mx_orders_customer ON public.mx_orders (customer_id) WHERE total > 0;
CREATE INDEX mx_customers_lower_email ON public.mx_customers (lower(email::text));
CREATE TABLE public.mx_events (id bigint, at date NOT NULL, body text) PARTITION BY RANGE (at);
CREATE TABLE public.mx_events_2026 PARTITION OF public.mx_events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
CREATE TABLE public.mx_events_2027 PARTITION OF public.mx_events FOR VALUES FROM ('2027-01-01') TO ('2028-01-01');
CREATE TABLE public.mx_plans (id int PRIMARY KEY, name text NOT NULL, price numeric(8,2));
INSERT INTO public.mx_plans VALUES (1, 'free', 0), (2, 'pro', 25), (3, 'team', 99);
CREATE TABLE mx_app.mx_settings (key text PRIMARY KEY, value jsonb NOT NULL);
CREATE VIEW public.mx_order_totals AS
  SELECT c.id, c.name, sum(o.total) AS spent FROM public.mx_customers c JOIN public.mx_orders o ON o.customer_id = c.id GROUP BY c.id, c.name;
CREATE VIEW public.mx_big_spenders AS SELECT * FROM public.mx_order_totals WHERE spent > 100;
CREATE MATERIALIZED VIEW public.mx_daily AS SELECT at, count(*) AS n FROM public.mx_events GROUP BY at;
CREATE FUNCTION public.mx_gross(n numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$ SELECT round(n * 1.2, 2) $$;
CREATE FUNCTION public.mx_touch() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.created_at := now(); RETURN NEW; END $$;
CREATE TRIGGER mx_customers_touch BEFORE INSERT ON public.mx_customers FOR EACH ROW EXECUTE FUNCTION public.mx_touch();
CREATE FUNCTION public.mx_double(a int) RETURNS int LANGUAGE sql IMMUTABLE BEGIN ATOMIC SELECT a * 2; END;
CREATE AGGREGATE public.mx_concat(text) (SFUNC = textcat, STYPE = text, INITCOND = '');
CREATE TABLE public.mx_audit (id int, note text);
CREATE RULE mx_audit_no_delete AS ON DELETE TO public.mx_audit DO INSTEAD NOTHING;
COMMENT ON TABLE public.mx_customers IS 'Customers';
COMMENT ON COLUMN public.mx_orders.total IS 'Net total';
ALTER TABLE public.mx_orders ENABLE ROW LEVEL SECURITY;
CREATE POLICY mx_orders_read ON public.mx_orders FOR SELECT TO mx_reader USING (total > 0);
GRANT USAGE ON SCHEMA mx_app TO mx_reader;
GRANT SELECT ON public.mx_customers, public.mx_order_totals TO mx_reader;
GRANT SELECT (id, total) ON public.mx_orders TO mx_reader;
ALTER DEFAULT PRIVILEGES IN SCHEMA mx_app GRANT SELECT ON TABLES TO mx_reader;
ALTER TABLE public.mx_customers REPLICA IDENTITY FULL;
ALTER TABLE public.mx_orders ALTER COLUMN kind SET STATISTICS 300;
CREATE STATISTICS public.mx_orders_stats (dependencies) ON customer_id, kind FROM public.mx_orders;
CREATE TEXT SEARCH CONFIGURATION public.mx_simple (COPY = pg_catalog.simple);
SQL
  # What only some versions have, named mx_v* so the shared state leaves it out.
  [ $v -ge 15 ] && echo "CREATE VIEW public.mx_v15_secure WITH (security_invoker = true) AS SELECT id FROM public.mx_customers;
CREATE TABLE public.mx_v15_codes (code text UNIQUE NULLS NOT DISTINCT);"
  [ $v -ge 17 ] && echo "GRANT MAINTAIN ON public.mx_plans TO mx_reader;"
  [ $v -ge 18 ] && echo "CREATE TABLE public.mx_v18_virtual (a int, b int GENERATED ALWAYS AS (a * 2) VIRTUAL);"
  [ $kind = sb ] && cat <<'SQL'
ALTER TABLE public.mx_customers ENABLE ROW LEVEL SECURITY;
CREATE POLICY mx_customers_own ON public.mx_customers FOR SELECT TO authenticated USING (auth.uid() IS NOT NULL);
GRANT SELECT ON public.mx_order_totals TO anon;
SQL
}
# The platform's parts of a Supabase fixture, which only its admin may make.
sb_admin_fixture(){ cat <<'SQL'
SELECT cron.schedule('mx-nightly', '0 3 * * *', 'SELECT 1');
SELECT pgmq.create('mx_jobs');
ALTER PUBLICATION supabase_realtime ADD TABLE public.mx_orders;
SQL
}

# The source moving on, once the target has rows of its own.
evolve(){ cat <<'SQL'
ALTER TABLE public.mx_customers RENAME COLUMN name TO full_name;
ALTER TABLE mx_app.mx_settings RENAME TO mx_config;
ALTER TABLE public.mx_orders ADD COLUMN note text;
ALTER TYPE public.mx_status ADD VALUE 'refunded';
CREATE OR REPLACE FUNCTION public.mx_gross(n numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$ SELECT round(n * 1.25, 2) $$;
DROP VIEW public.mx_big_spenders;
DROP VIEW public.mx_order_totals;
DROP POLICY mx_orders_read ON public.mx_orders;
ALTER TABLE public.mx_orders DROP COLUMN total_gross;
ALTER TABLE public.mx_orders ALTER COLUMN total TYPE numeric(14,2);
ALTER TABLE public.mx_orders ADD COLUMN total_gross numeric(16,2) GENERATED ALWAYS AS (total * 1.2) STORED;
CREATE VIEW public.mx_order_totals AS
  SELECT c.id, c.full_name AS name, sum(o.total) AS spent, count(*) AS orders FROM public.mx_customers c JOIN public.mx_orders o ON o.customer_id = c.id GROUP BY c.id, c.full_name;
CREATE VIEW public.mx_big_spenders AS SELECT * FROM public.mx_order_totals WHERE spent > 100;
GRANT SELECT ON public.mx_order_totals TO mx_reader;
CREATE POLICY mx_orders_read ON public.mx_orders FOR SELECT TO mx_reader USING (total > 0);
SQL
}
TARGET_ROWS="INSERT INTO public.mx_customers (email, name) VALUES ('a@x.io', 'Ann'), ('b@x.io', 'Bo'), ('c@x.io', 'Cy');
INSERT INTO public.mx_orders (customer_id, total, kind) SELECT id, 150, 'web' FROM public.mx_customers WHERE email IN ('a@x.io', 'b@x.io');
INSERT INTO mx_app.mx_settings VALUES ('plan', '{\"tier\":\"pro\"}'), ('flags', '{\"beta\":true}');"

# What both sides must agree on: the fixture, version-specific objects aside.
STATE="SELECT concat_ws(' ',
 (SELECT string_agg(relname || ':' || relkind::text, ',' ORDER BY relname) FROM pg_class WHERE relnamespace IN ('public'::regnamespace, to_regnamespace('mx_app')) AND relname LIKE 'mx\_%' AND relname NOT LIKE 'mx\_v1%' AND relkind IN ('r','p','v','m','S','i')),
 (SELECT string_agg(proname, ',' ORDER BY proname) FROM pg_proc WHERE pronamespace = 'public'::regnamespace AND proname LIKE 'mx\_%'),
 (SELECT string_agg(typname, ',' ORDER BY typname) FROM pg_type WHERE typnamespace = 'public'::regnamespace AND typname LIKE 'mx\_%' AND typname NOT LIKE 'mx\_v1%' AND typtype IN ('e','d','c','r')),
 (SELECT string_agg(polname, ',' ORDER BY polname) FROM pg_policy WHERE polname = 'mx_orders_read'),
 (SELECT count(*) FROM pg_rewrite WHERE rulename = 'mx_audit_no_delete'),
 (SELECT count(*) FROM pg_statistic_ext WHERE stxname = 'mx_orders_stats'),
 (SELECT count(*) FROM pg_ts_config WHERE cfgname = 'mx_simple'),
 (SELECT relreplident FROM pg_class WHERE oid = to_regclass('public.mx_customers')),
 (SELECT attstattarget FROM pg_attribute WHERE attrelid = to_regclass('public.mx_orders') AND attname = 'kind'),
 (SELECT count(*) FROM pg_default_acl WHERE defaclnamespace = to_regnamespace('mx_app')),
 (SELECT has_table_privilege('mx_reader', 'public.mx_customers', 'SELECT')),
 (SELECT CASE WHEN to_regnamespace('mx_app') IS NULL THEN 'no-schema' ELSE has_schema_privilege('mx_reader', 'mx_app', 'USAGE')::text END),
 (SELECT has_column_privilege('mx_reader', 'public.mx_orders', 'total', 'SELECT')),
 (SELECT obj_description('public.mx_customers'::regclass, 'pg_class')),
 (SELECT string_agg(enumlabel, '|' ORDER BY enumsortorder) FROM pg_enum WHERE enumtypid = to_regtype('public.mx_status')),
 (SELECT count(*) FROM public.mx_plans))"
P2="SELECT concat_ws(' ', (SELECT count(full_name) FROM public.mx_customers), (SELECT count(*) FROM public.mx_orders),
 (SELECT count(*) FROM mx_app.mx_config), (SELECT public.mx_gross(100)),
 (SELECT format_type(atttypid, atttypmod) FROM pg_attribute WHERE attrelid = 'public.mx_orders'::regclass AND attname = 'total'),
 (SELECT sum(total_gross) FROM public.mx_orders), (SELECT count(*) FROM public.mx_big_spenders))"

row(){ printf '%s\t%s\t%s\n' "$1" "$2" "$3" | tee -a $RES; }
sfrun(){ (cd $WS && NO_COLOR=1 timeout 900 node $SF/bin/run.js "$@" 2>&1); }
# fixture issues left after an apply (titles naming mx_ objects), version-specific ones aside
leftover(){ (cd $WS && NO_COLOR=1 node $SF/bin/run.js diff --check schema --json 2>/dev/null) | MX_TARGET_PLAIN=$MX_TARGET_PLAIN node -e "
  let j; try { j = JSON.parse(require('fs').readFileSync(0,'utf8')) } catch { console.log('UNREADABLE'); process.exit() }
  // What only Supabase can hold (a policy calling auth.uid()) is left out of a plain target by design.
  const plain = process.env.MX_TARGET_PLAIN === '1'
  const t = j.checks.flatMap(c => c.issues.map(i => i.title)).filter(t => /mx_/.test(t) && !/mx_v1/.test(t) && !(plain && /mx_customers_own/.test(t)))
  console.log(t.join(' ; '))"; }


# Roles both servers need, and on Supabase what the project's queues and cron
# jobs need: what a Supabase project has once they are enabled.
prep(){ local kind=$1 c=$2 p=$3
  q $kind $c $p postgres -c "DO \$\$ BEGIN CREATE ROLE mx_reader NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END \$\$" >/dev/null
  [ $kind = sb ] || return 0
  q sb $c $p postgres -c "CREATE EXTENSION IF NOT EXISTS pg_cron" -c "GRANT USAGE ON SCHEMA cron TO postgres" \
    -c "GRANT ALL ON ALL TABLES IN SCHEMA cron TO postgres" -c "CREATE EXTENSION IF NOT EXISTS pgmq" -c "GRANT mx_reader TO postgres" \
    -c "GRANT USAGE, CREATE ON SCHEMA pgmq TO postgres" -c "GRANT ALL ON ALL TABLES IN SCHEMA pgmq TO postgres" \
    -c "GRANT ALL ON ALL SEQUENCES IN SCHEMA pgmq TO postgres" -c "GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA pgmq TO postgres" >/dev/null
}

# Fresh servers: a plain database is made, a Supabase one is its postgres.
reset(){ local kind=$1 c=$2 p=$3 db=$4
  [ $kind = sb ] || q pg $c $p postgres -c "DROP DATABASE IF EXISTS $db WITH (FORCE)" -c "CREATE DATABASE $db" >/dev/null; }
pair(){ local s=$1 t=$2 name="$1>$2"
  read sk sv sc sp <<< "$(info $s src)"; read tk tv tc tp <<< "$(info $t tgt)"
  local sdb=mx_s tdb=mx_t; [ $sk = sb ] && sdb=postgres; [ $tk = sb ] && tdb=postgres
  MX_TARGET_PLAIN=$([ $sk = sb ] && [ $tk = pg ] && echo 1 || echo 0)
  [ "$sc" = "$tc" ] && [ $sk = pg ] || true
  echo "== $name"
  WS=$OUT/ws-${s}-${t}; rm -rf $WS; mkdir -p $WS
  reset $sk $sc $sp $sdb; reset $tk $tc $tp $tdb
  if ! fixture $sk $sv | qu $sk $sc $sp $sdb > $WS/fixture.log 2>&1 \
     || { [ $sk = sb ] && ! sb_admin_fixture | q sb $sc $sp $sdb >> $WS/fixture.log 2>&1; }; then
    row "$name" setup "FAIL fixture: $(grep -m1 ERROR $WS/fixture.log)"; return; fi
  local rdb=mx_r
  printf '{ "environments": { "src": { "dbUrl": "%s" }, "tgt": { "dbUrl": "%s" }%s }, "source": "src", "target": "tgt", "checks": { "data": { "tables": ["mx_plans"] } } }\n' \
    "$(url $sk $sc $sp $sdb)" "$(url $tk $tc $tp $tdb)" "$([ $tk = pg ] && printf ', "rst": { "dbUrl": "%s" }' "$(url pg $tc $tp $rdb)")" > $WS/supaforge.config.json
  local want got left t0=$SECONDS

  # p1: first sync
  sfrun diff --apply > $WS/p1.apply; local c1=$?
  want=$(qu $sk $sc $sp $sdb -c "$STATE" 2>&1); got=$(qu $tk $tc $tp $tdb -c "$STATE" 2>&1)
  left=$(leftover)
  if [[ "$want" == *mx_customers:r* ]] && [ "$want" = "$got" ] && [ -z "$left" ]; then row "$name" p1 "PASS exit=$c1 $((SECONDS-t0))s"
  else row "$name" p1 "FAIL exit=$c1 $( [ "$want" != "$got" ] && echo "state differs: $(diff <(tr ' ' '\n' <<< "$want") <(tr ' ' '\n' <<< "$got") | grep '^[<>]' | tr '\n' ' ' | head -c 400)") left=[$left] err=[$(grep -E '✗|✖|error' $WS/p1.apply | head -3 | tr '\n' ' ' | head -c 400)]"; fi

  # p2: the target has rows; the source moves on
  t0=$SECONDS
  if qu $tk $tc $tp $tdb -c "$TARGET_ROWS" > $WS/rows.log 2>&1 && evolve | qu $sk $sc $sp $sdb > $WS/evolve.log 2>&1; then
    sfrun diff --check schema --apply --prove > $WS/p2.apply; local c2=$?
    local proved=yes; grep -q "Not proven\|Not proved:\|does not reproduce" $WS/p2.apply && proved=no
    if [ $proved = no ] && grep -q "Nothing was applied" $WS/p2.apply; then
      sfrun diff --check schema --apply > $WS/p2b.apply; c2="$c2/then-unproved:$?"
    fi
    want=$(qu $sk $sc $sp $sdb -c "$STATE" 2>&1); got=$(qu $tk $tc $tp $tdb -c "$STATE" 2>&1)
    local rows=$(qu $tk $tc $tp $tdb -c "$P2" 2>&1); left=$(leftover)
 if [[ "$want" == *mx_customers:r* ]] && [ "$want" = "$got" ] && [ -z "$left" ] && [ "$rows" = "3 2 2 125.00 numeric(14,2) 360.00 2" ]; then row "$name" p2 "PASS exit=$c2 proved=$proved $((SECONDS-t0))s"
    else row "$name" p2 "FAIL exit=$c2 proved=$proved rows=[$rows] $( [ "$want" != "$got" ] && echo "state differs: $(diff <(tr ' ' '\n' <<< "$want") <(tr ' ' '\n' <<< "$got") | grep '^[<>]' | tr '\n' ' ' | head -c 400)") left=[$left] why=[$(grep -E '✗|✖|rows lost|differ|unexpected|missing' $WS/p2.apply | head -4 | tr '\n' ' ' | head -c 500)]"; fi
  else row "$name" p2 "FAIL setup: $(grep -m1 ERROR $WS/rows.log $WS/evolve.log)"; fi

  # p3: snapshot the source, restore into a fresh plain database
  if [ $tk = pg ]; then
    t0=$SECONDS; reset pg $tc $tp $rdb
    sfrun snapshot --env src --apply > $WS/p3.snap; local cs=$?
    sfrun restore --env rst --from-snapshot=latest --apply > $WS/p3.restore; local cr=$?
    want=$(qu $sk $sc $sp $sdb -c "$STATE" 2>&1); got=$(q pg $tc $tp $rdb -c "$STATE" 2>&1)
    if [[ "$want" == *mx_customers:r* ]] && [ "$want" = "$got" ]; then row "$name" p3 "PASS snapshot=$cs restore=$cr $((SECONDS-t0))s"
    else row "$name" p3 "FAIL snapshot=$cs restore=$cr state differs: $(diff <(tr ' ' '\n' <<< "$want") <(tr ' ' '\n' <<< "$got") | grep '^[<>]' | tr '\n' ' ' | head -c 400) err=[$(grep -E '✖|error' $WS/p3.restore | head -2 | tr '\n' ' ' | head -c 300)]"; fi
  fi
}


read sk _ sc sp <<< "$(info $SOURCE src)"; read tk _ tc tp <<< "$(info $TARGET tgt)"
start $SOURCE $sc $sp; start $TARGET $tc $tp
prep $sk $sc $sp; prep $tk $tc $tp
pair $SOURCE $TARGET
docker rm -f mx-src mx-tgt >/dev/null 2>&1
echo; echo "== $SOURCE>$TARGET: $(grep -c PASS "$RES") pass, $(grep -c FAIL "$RES") fail"
! grep -q FAIL "$RES"
